# 自然单位（需要单重表）：个 只 根 块 片 瓣 条 颗 粒 串
_NATURAL_UNITS = {"个", "只", "根", "块", "片", "瓣", "条", "颗", "粒", "串", "枚", "支", "头", "把", "棵"}


def _to_num(s: str) -> float | None:
    """把数字字符串/汉字数量转 float"""
    s = s.strip()
    if not s:
        return None
    try:
        return float(s)
    except ValueError:
        pass
    return _CN_NUM.get(s)


def _split_ingredients(text: str) -> list[str]:
    parts = re.split(r"[,，、;；/\\\n\r]+", text)
    return [p.strip() for p in parts if p.strip()]


# 数量+单位 正则：分支1 阿拉伯数字（单位可选）；分支2 汉字数字（必须带单位，
# 避免"五花肉"的"五"被误认为数量）
_QTY_RE = re.compile(
    r"([\d.]+)\s*(个|只|根|块|片|瓣|条|颗|粒|串|枚|支|头|把|棵|克|g|G|斤|两|公斤|千克|kg|KG|磅|毫升|ml|ML|升|L)?"
    r"|(半|[一二两三四五六七八九十]+)\s*(个|只|根|块|片|瓣|条|颗|粒|串|枚|支|头|把|棵|克|斤|两|公斤|千克|磅|毫升|升)"
)


def _parse_one(part: str) -> dict | None:
    """解析单个原料条目 → {name, grams, unit, qty, seasoning, estimated}"""
    # 先定位"数量+单位"（如 2个/半根/200克/1斤），数量之前的部分是原料名
    m2 = _QTY_RE.search(part)
    if m2:
        if m2.group(1) is not None:
            qty = _to_num(m2.group(1)) or 1.0
            unit = m2.group(2)
        else:
            qty = _to_num(m2.group(3)) or 1.0
            unit = m2.group(4)
        name = part[:m2.start()].strip()
    else:
        name = part.strip()
        qty = 1.0
        unit = None
    if not name:
        return None

    # 调味料：不计热量（含"油"单独出现）
    if name in _SEASONINGS or any(s in name for s in _SEASONINGS):
        return {"name": name, "grams": 0, "seasoning": True, "estimated": False}

    if unit in _UNIT_TO_G:
        grams = qty * _UNIT_TO_G[unit]
        estimated = False
    elif unit in _NATURAL_UNITS:
        base = _UNIT_WEIGHT.get(name)
        if base:
            grams = qty * base
            estimated = False  # 按默认单重估算，标记半估算
        else:
            grams = qty * 100  # 未知食材默认 100g/个
            estimated = True
    else:
        # 无单位/适量：默认 100g
        grams = 100.0
        estimated = True

    return {
        "name": name, "grams": round(grams, 1), "unit": unit,
        "qty": qty, "seasoning": False, "estimated": estimated,
    }


def parse_ingredients(text: str) -> list[dict]:
    """解析原料文本 → [{name, grams, seasoning, estimated}]（调味料 grams=0）"""
    out = []
    for part in _split_ingredients(text):
        item = _parse_one(part)
        if item:
            out.append(item)
    return out
